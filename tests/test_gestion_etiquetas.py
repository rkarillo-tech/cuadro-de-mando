    pg.fill('#tgDesc','Reuniones de seguimiento'); pg.keyboard.press('Enter'); pg.wait_for_timeout(150)
    ok(pg.evaluate("tagMetaOf('reunion').desc")=='Reuniones de seguimiento' and pg.evaluate("tagMetaOf('reunion').color")=='verde','guardar la descripción')
