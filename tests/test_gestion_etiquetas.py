    ok(pg.evaluate("tagSel")=='reunion','cambiar de etiqueta desde la nube')
    ok(pg.evaluate("currentTab")=='tags','sigue en la sección Etiquetas')
    # ===== Crear =====
    pg.click('#tgNew'); pg.wait_for_timeout(200)
    pg.keyboard.type('Cliente ACME'); pg.wait_for_timeout(100)
    ok('#Cliente-ACME' in pg.inner_text('#ntInfo'),'avisa de cómo se guardará el nombre')
