    pg.click('.modal-foot .btn.danger-solid'); pg.wait_for_timeout(500)
    r=pg.evaluate("[tagIndex().has('reunion'), tagIndex().has('reunion/semanal'), S.todos.find(t=>t.text.startsWith('Preparar')).text, S.notes.find(n=>n.title==='Acta comité').text, S.todos.find(t=>t.text==='Enviar acta').tags||[], tagMetaOf('reunion')]")
