    pg.evaluate("openTagView('cliente-acme')"); pg.wait_for_timeout(200)
    pg.click('#tgDetail [data-tga="assign"]'); pg.wait_for_timeout(250)
    ok(pg.locator('#asList .as-row').count()>=5,'lista de elementos de todas las secciones')
    pg.fill('#asQ','llamar'); pg.wait_for_timeout(250)
    ok(pg.locator('#asList .as-row').count()==1,'buscar en la lista')
