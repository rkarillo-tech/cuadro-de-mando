    pg.click('.modal-foot .btn.primary'); pg.wait_for_timeout(250)
    ok(pg.evaluate("tagSel")=='cliente-acme' and pg.evaluate("tagIndex().get('cliente-acme').count")==0,'crear una etiqueta sin uso todavía')
    ok(pg.evaluate("tagColorId('cliente-acme')")=='naranja' and pg.evaluate("tagMetaOf('cliente-acme').desc")=='Todo lo del cliente ACME','con color y descripción')
    ok(pg.locator('#tgCloud .cloud-tag.unused[data-tag="cliente-acme"]').count()==1,'aparece en la nube (atenuada, sin uso)')
    ok('Todavía no la lleva ningún elemento' in pg.inner_text('#tgDetail'),'detalle de una etiqueta sin uso')
    pg.evaluate("showTab('notes')"); pg.click('#noteTagAdd'); pg.wait_for_timeout(150)
    ok('cliente-ACME' in pg.inner_text('#tagPicker') or 'Cliente-ACME' in pg.inner_text('#tagPicker'),'la etiqueta creada sale en el desplegable de las notas'); pg.keyboard.press('Escape')
