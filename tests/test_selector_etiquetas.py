    ok(pg.locator('#notesList .note-item').count()==1 and 'Informe portal' in pg.inner_text('#notesList'),'filtrar notas por #proyecto incluye #proyecto/portal')
    pg.evaluate("setNotesMode('tree')"); pg.wait_for_timeout(200)
    ok(pg.locator('#notesList .wk-row').count()==1,'el filtro también vale en el árbol de la wiki')
    pg.evaluate("setNotesMode('list'); setTagFilter('notes',null)")
    pg.evaluate("showTab('kanban'); S.tasks.push({id:'k2',title:'Otra',desc:'',col:'todo',priority:'media',due:'',tags:[],subtasks:[],created:Date.now()});save.tasks(); setTagFilter('kanban','legal')"); pg.wait_for_timeout(200)
    ok(pg.locator('#kbBoard .kb-card').count()==1,'Kanban filtrado por etiqueta')
    pg.evaluate("setTagFilter('kanban',null); showTab('todos'); setTagFilter('todos','cliente-acme')"); pg.wait_for_timeout(200)
