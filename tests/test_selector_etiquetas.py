import os as _os, sys as _sys, tempfile as _tf
_ROOT = _os.path.abspath(_os.path.join(_os.path.dirname(__file__), '..'))
_HTML = 'file://' + _os.path.join(_ROOT, 'CuadroDeMando.html')
if len(_sys.argv) < 2: _sys.argv.append(_tf.mkdtemp(prefix='cdm-test-'))
import sys
from playwright.sync_api import sync_playwright
URL=_HTML
SC=sys.argv[1]
errs=[]; fails=[]
def ok(c,m):
    print(('PASS ' if c else 'FAIL ')+m, flush=True)
    if not c: fails.append(m)
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':1400,'height':900}); pg=ctx.new_page()
    pg.on('pageerror', lambda e: errs.append('PAGEERR '+str(e)))
    pg.on('console', lambda m: errs.append('console:'+m.text) if m.type=='error' else None)
    pg.goto(URL); pg.wait_for_timeout(900); pg.evaluate("localStorage.clear(); indexedDB.deleteDatabase('cdm-data'); indexedDB.deleteDatabase('cdm-hist'); 0"); pg.goto('about:blank'); pg.goto(URL); pg.wait_for_timeout(900)
    nid=pg.evaluate("""()=>{const a=createNote('Informe portal','<div>Avance del #proyecto/portal</div>',false);
      createNote('Receta','<div>Sin etiquetas</div>',false);
      addTodoFromText('Revisar contrato #cliente-acme','inbox');
      S.tasks.push({id:'k1',title:'Desplegar',desc:'',col:'todo',priority:'media',due:'',tags:['urgente'],subtasks:[],created:Date.now()});save.tasks();
      S.bookmarks.push({id:'b1',title:'Portal',url:'https://ejemplo.es',category:'',notes:'',created:Date.now(),visits:0});save.bookmarks();
      return a.id}""")
    # ===== Nota: barra de etiquetas y desplegable =====
    pg.evaluate(f"showTab('notes'); openNote({nid!r})"); pg.wait_for_timeout(250)
    ok(pg.is_visible('#noteTags') and pg.locator('#noteTags .tf-chip.inline').count()==1,'la nota muestra su etiqueta escrita en el texto (discontinua)')
    pg.click('#noteTagAdd'); pg.wait_for_timeout(200)
    ok(pg.is_visible('#tagPicker') and pg.locator('#tagPicker .tp-row').count()>=4,'el botón abre el desplegable con todas las etiquetas')
    ok(pg.evaluate("document.activeElement.classList.contains('tp-q')"),'el buscador del desplegable recibe el foco')
    t=pg.inner_text('#tagPicker .tp-list')
    ok(t.index('portal')<t.index('urgente'),'las de la nota salen primero')
    pg.click('#tagPicker .tp-row:has-text("urgente")'); pg.wait_for_timeout(200)
    ok(pg.evaluate(f"getNote({nid!r}).tags")==['urgente'],'marcar una etiqueta la añade a la nota')
    ok(pg.is_visible('#tagPicker'),'el desplegable sigue abierto para marcar varias')
    pg.keyboard.type('Comité Dirección'); pg.wait_for_timeout(200)
    ok('Crear #Comité-Dirección' in pg.inner_text('#tagPicker'),'propone crear una nueva (espacios → guiones)')
    pg.keyboard.press('Enter'); pg.wait_for_timeout(200)
    ok(pg.evaluate(f"getNote({nid!r}).tags")==['urgente','Comité-Dirección'],'Enter crea y añade la nueva')
    pg.keyboard.type('portal'); pg.wait_for_timeout(150); pg.keyboard.press('Enter'); pg.wait_for_timeout(200)
    ok(pg.evaluate(f"getNote({nid!r}).tags")==['urgente','Comité-Dirección'],'la escrita en el texto no se puede quitar desde el desplegable')
    pg.keyboard.press('Escape'); pg.wait_for_timeout(150)
    ok(not pg.is_visible('#tagPicker'),'Esc cierra el desplegable')
    ok(pg.locator('#noteTags .tf-chip:not(.inline)').count()==2,'chips de la nota con su ×')
    pg.click('#noteTags .tf-x[data-x="urgente"]'); pg.wait_for_timeout(200)
    ok(pg.evaluate(f"getNote({nid!r}).tags")==['Comité-Dirección'],'la × quita la etiqueta')
    ok(pg.evaluate("tagItemsOf('comite-direccion').length")==1 and 'Comité-Dirección' in pg.inner_text('#notesList'),'entra en el índice y se ve en la lista de notas')
    html=pg.evaluate(f"getNote({nid!r}).html")
    ok('Comité' not in html,'el desplegable no toca el texto de la nota')
    # ===== Colores =====
    c1=pg.evaluate("getComputedStyle(document.querySelector('#noteTags .tf-chip:not(.inline)')).color")
    pg.evaluate("tagSetColor('comite-direccion','verde')"); pg.wait_for_timeout(150)
    c2=pg.evaluate("getComputedStyle(document.querySelector('#noteTags .tf-chip:not(.inline)')).color")
    ok(c1!=c2,'cambiar el color repinta el chip: '+c1+' → '+c2)
    ok(pg.evaluate("tagColorId('comite-direccion')")=='verde' and pg.evaluate("store.get('tagMeta',{})['comite-direccion'].color")=='verde','el color se guarda')
    pg.evaluate("tagSetColor('proyecto','rojo')")
    ok(pg.evaluate("tagColorId('proyecto/portal')")=='rojo' and pg.evaluate("tagColorSrc('proyecto/portal').from")=='proyecto','las subetiquetas heredan el color del padre')
    ok(pg.evaluate("tagPal('xyz').id")==pg.evaluate("tagPal('xyz').id") and pg.evaluate("tagColorId('xyz')") is None,'sin color propio: tono automático estable')
    pg.click('#noteTagAdd'); pg.wait_for_timeout(150)
    pg.click('#tagPicker .tp-dot[data-dot="urgente"]'); pg.wait_for_timeout(150)
    ok(pg.locator('#tagPicker .tp-palrow .tp-sw').count()==13,'el punto de color abre la paleta (12 + automático)')
    pg.click('#tagPicker .tp-palrow [data-col="azul"]'); pg.wait_for_timeout(150)
    ok(pg.evaluate("tagColorId('urgente')")=='azul','elegir color desde el desplegable')
    pg.keyboard.press('Escape')
    pg.evaluate("openTagView('urgente')"); pg.wait_for_timeout(250)
    ok(pg.locator('#tgDetail .tg-colrow .tp-sw').count()==13,'la vista de la etiqueta tiene su paleta')
    pg.click('#tgDetail .tg-colrow [data-col="auto"]'); pg.wait_for_timeout(150)
    ok(pg.evaluate("tagColorId('urgente')") is None and 'automático' in pg.inner_text('#tgDetail .tg-colrow'),'volver a color automático')
    # ===== Formularios: tarea, tarjeta, evento, marcador =====
    tid=pg.evaluate("S.todos[0].id")
    pg.evaluate(f"showTab('todos'); openTodo({tid!r}); 0"); pg.wait_for_timeout(250)
    ok(pg.locator('#modal .tag-field .tf-chip.inline').count()==1,'la tarea muestra la etiqueta del texto en el campo')
    pg.click('#modal .tf-add'); pg.wait_for_timeout(150)
    pg.keyboard.type('urg'); pg.wait_for_timeout(120); pg.keyboard.press('Enter'); pg.wait_for_timeout(150)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(150)
    ok(pg.is_visible('#modal'),'Esc cierra solo el desplegable, no el formulario')
    pg.fill('#modal input[name=text]','Revisar contrato #cliente-acme #legal'); pg.wait_for_timeout(350)
    ok(pg.locator('#modal .tag-field .tf-chip.inline').count()==2,'el campo se actualiza al escribir #etiquetas en el texto')
    pg.click('.modal-foot .btn.primary'); pg.wait_for_timeout(200)
    ok(pg.evaluate(f"S.todos.find(t=>t.id==={tid!r}).tags")==['urgente'],'la tarea guarda sus etiquetas')
    pg.evaluate("setTodoView('all')"); pg.wait_for_timeout(150)
    ok(pg.locator('#todoItems .tg-pill[data-tag="urgente"]').count()==1,'chip de color en la lista de tareas')
    pg.evaluate("openTask('k1'); 0"); pg.wait_for_timeout(250)
    ok(pg.locator('#modal .tag-field .tf-chip:not(.inline)').count()==1 and not pg.locator('#modal input[name=tags][type=text]').count(),'Kanban: el campo de texto pasa a chips')
    pg.click('#modal .tf-x'); pg.click('#modal .tf-add'); pg.wait_for_timeout(150)
    pg.keyboard.type('legal'); pg.wait_for_timeout(120); pg.keyboard.press('Enter'); pg.keyboard.press('Escape'); pg.wait_for_timeout(100)
    pg.click('.modal-foot .btn.primary'); pg.wait_for_timeout(200)
    ok(pg.evaluate("S.tasks[0].tags")==['legal'],'Kanban guarda las etiquetas del desplegable')
    pg.evaluate("openEvent(null, todayKey()); 0"); pg.wait_for_timeout(250)
    pg.fill('#modal input[name=title]','Comité'); pg.click('#modal .tf-add'); pg.wait_for_timeout(150)
    pg.click('#tagPicker .tp-row:has-text("Comité-Dirección")'); pg.keyboard.press('Escape'); pg.wait_for_timeout(100)
    pg.click('.modal-foot .btn.primary'); pg.wait_for_timeout(200)
    ok(pg.evaluate("S.events[0].tags")==['Comité-Dirección'],'los eventos también tienen el selector')
    pg.evaluate("showTab('bookmarks'); openBookmark('b1'); 0"); pg.wait_for_timeout(250)
    pg.click('#modal .tf-add'); pg.wait_for_timeout(150); pg.keyboard.type('legal'); pg.keyboard.press('Enter'); pg.keyboard.press('Escape'); pg.wait_for_timeout(100)
    pg.click('.modal-foot .btn.primary'); pg.wait_for_timeout(200)
    ok(pg.evaluate("S.bookmarks[0].tags")==['legal'] and pg.locator('#bmList .tg-pill').count()==1,'marcadores: selector y chips en la tarjeta')
    ok(sorted(pg.evaluate("tagItemsOf('legal').map(x=>x.kind)"))==['bookmark','kanban','todo'],'la etiqueta reúne lo puesto con el selector y lo escrito')
    # ===== Filtros =====
    pg.click('#view-bookmarks [data-tagf-open]'); pg.wait_for_timeout(150)
    ok('Todas (sin filtro)' in pg.inner_text('#tagPicker'),'el filtro ofrece «Todas»')
    pg.keyboard.type('legal'); pg.keyboard.press('Enter'); pg.wait_for_timeout(200)
    ok(pg.evaluate("tagFilters.bookmarks")=='legal' and not pg.is_visible('#tagPicker'),'elegir filtro cierra el desplegable')
    pg.evaluate("S.bookmarks.push({id:'b2',title:'Otro',url:'https://otro.es',category:'',notes:'',created:Date.now(),visits:0});save.bookmarks();renderBookmarks()")
    ok(pg.locator('#bmList .bm-card').count()==1,'marcadores filtrados por etiqueta')
    pg.click('#view-bookmarks [data-tagf-clear]'); pg.wait_for_timeout(150)
    ok(pg.locator('#bmList .bm-card').count()==2,'quitar el filtro')
