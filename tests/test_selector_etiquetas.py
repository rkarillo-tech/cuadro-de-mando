    pg.evaluate("reloadSafe()"); pg.wait_for_timeout(1300)
    ok(pg.evaluate(f"getNote({nid!r}).tags")==['Comité-Dirección'] and pg.evaluate("tagColorId('juridico')")=='violeta','etiquetas y colores sobreviven a recargar')
    ok(pg.evaluate("tagColorCss('juridico').startsWith('hsl(270')"),'el grafo usa el color de la etiqueta')
    pg.evaluate(f"showTab('notes'); openNote({nid!r})"); pg.wait_for_timeout(250)
    pg.click('#noteTagAdd'); pg.wait_for_timeout(200)
    pg.screenshot(path=SC+'/selector.png')
    pg.keyboard.press('Escape')
    pg.evaluate("openTagView('juridico')"); pg.wait_for_timeout(250); pg.screenshot(path=SC+'/colores.png')
