    m.evaluate(f"showTab('notes'); openNote({nid!r})"); m.wait_for_timeout(250)
    m.click('#noteTagAdd'); m.wait_for_timeout(200)
    bx=m.evaluate("(()=>{const r=tagPicker.getBoundingClientRect();return [r.left,r.right]})()")
    ok(bx[0]>=0 and bx[1]<=390 and m.evaluate("document.documentElement.scrollWidth")<=390,'desplegable dentro de la pantalla en móvil: '+str(bx))
    m.screenshot(path=SC+'/selector_movil.png')
    print('ERRORS:',errs); print('FAILS:',len(fails))
