    pg.evaluate("tagSetColor('legal','violeta'); tagRename('legal','juridico')")
    ok(pg.evaluate("S.tasks[0].tags")==['juridico'] and pg.evaluate("S.bookmarks[0].tags")==['juridico'] and pg.evaluate("tagColorId('juridico')")=='violeta' and pg.evaluate("tagColorId('legal')") is None,'renombrar cambia los campos y conserva el color')
